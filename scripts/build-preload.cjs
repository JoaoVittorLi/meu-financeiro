'use strict';
// Deterministic sandbox-safe preload build. Electron's sandboxed require()
// cannot import ./d05-preload-bridge.cjs. Compile the bridge into one file.
const fs=require('node:fs');
const path=require('node:path');

const ROOT=path.resolve(__dirname,'..');
const OUTPUT='electron/preload-bundled.cjs';
const BRIDGE_IMPORT="const {createD05PreloadBridge}=require('./d05-preload-bridge.cjs');";

function generate(root=ROOT){
 const source=fs.readFileSync(path.join(root,'electron/preload.cjs'),'utf8');
 const bridge=fs.readFileSync(path.join(root,'electron/d05-preload-bridge.cjs'),'utf8');
 if(source.split(BRIDGE_IMPORT).length!==2)
  throw Error('Preload: import único do bridge D05 ausente ou duplicado.');
 if(/\brequire\s*\(/.test(bridge))
  throw Error('Preload: bridge D05 ganhou dependência e precisa ser auditado.');
 const inline=[
  '// D05 bridge inlined at build time to preserve Electron sandbox:true.',
  'const {createD05PreloadBridge}=(()=>{',
  'const module={exports:{}};',
  bridge,
  'return module.exports;',
  '})();'
 ].join('\n');
 const result=source.replace(BRIDGE_IMPORT,inline);
 const imports=[...result.matchAll(/\brequire\s*\(\s*(['"])(.*?)\1\s*\)/g)]
  .map(match=>match[2]);
 if(imports.length!==1||imports[0]!=='electron')
  throw Error('Preload sandbox: somente require("electron") é permitido.');
 return '// GENERATED by scripts/build-preload.cjs. DO NOT EDIT.\n'+result;
}
function main(){
 const mode=process.argv[2]||'build',file=path.join(ROOT,OUTPUT),expected=generate();
 if(mode==='check'){
  if(!fs.existsSync(file)||fs.readFileSync(file,'utf8')!==expected)
   throw Error('Preload sandbox desatualizado: execute npm run compile.');
  console.log('PASS: preload em arquivo único, compatível com sandbox.');
 }else if(mode==='build'){
  fs.writeFileSync(file,expected,'utf8');
  console.log('Preload sandbox gerado: '+OUTPUT);
 }else throw Error('Uso: build-preload.cjs build|check');
}
if(require.main===module)try{main();}catch(error){console.error(error.message);process.exitCode=1;}
module.exports={generate,OUTPUT};
