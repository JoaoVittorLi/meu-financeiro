test('migração aditiva a partir de banco anterior preserva dados, Pluggy e saldo',()=>{
 const {DatabaseSync}=require('node:sqlite');
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'mf-migrate-'));const file=path.join(dir,'old.sqlite');
 const old=new DatabaseSync(file);
 old.exec(`CREATE TABLE profiles(profile TEXT PRIMARY KEY,initialized_at TEXT);
 CREATE TABLE transactions(profile TEXT,id TEXT,date TEXT,description TEXT,kind TEXT,amount_cents INTEGER,category TEXT,origin TEXT,PRIMARY KEY(profile,id));
 CREATE TABLE budgets(profile TEXT,category TEXT,amount_cents INTEGER,PRIMARY KEY(profile,category));
 CREATE TABLE financial_settings(profile TEXT,name TEXT,value_cents INTEGER,PRIMARY KEY(profile,name));
 CREATE TABLE bank_items(item_id TEXT PRIMARY KEY,institution TEXT,status TEXT,consent_expires_at TEXT,last_sync_at TEXT);
 CREATE TABLE bank_accounts(account_id TEXT PRIMARY KEY,item_id TEXT,name TEXT,subtype TEXT,currency TEXT,balance_cents INTEGER,updated_at TEXT);
 CREATE TABLE bank_transactions(account_id TEXT,external_id TEXT,date TEXT,description TEXT,amount_cents INTEGER,status TEXT,category TEXT,updated_at TEXT,PRIMARY KEY(account_id,external_id));
 CREATE TABLE bank_sync_history(id INTEGER PRIMARY KEY AUTOINCREMENT,item_id TEXT,completed_at TEXT,new_count INTEGER,total_count INTEGER);
 CREATE TABLE app_meta(key TEXT PRIMARY KEY,value TEXT);
 INSERT INTO profiles VALUES('real','2026-11-06');
 INSERT INTO transactions VALUES('real','legacy1','2026-11-06','Despesa antiga','expense',1234,'Saúde','manual');
 INSERT INTO budgets VALUES('real','Saúde',80000);
 INSERT INTO bank_items VALUES('${ITEM}','Itau','UPDATED',NULL,NULL);
 INSERT INTO bank_accounts VALUES('${ACCOUNT}','${ITEM}','Itaú','BANK','BRL',34000,'2026-11-06');
 INSERT INTO bank_transactions VALUES('${ACCOUNT}','${TX}','2026-11-06','IFOOD',-3900,'POSTED','Outros','2026-11-06');`);
 old.close();
 const db=new FinanceDB(file);
 assert.equal(db.load('real').transactions[0].amount,1234);
 assert.equal(db.load('real').budgets['Saúde'],80000);
 assert.equal(db.bankOverview().accounts[0].balance,34000);
 assert.equal(db.bankOverview().transactions[0].amount,-3900);
 db.upsertRule({pattern:'IFOOD',category:'Alimentação',priority:10,matchMode:'contains',scope:'bank'});
 assert.equal(db.bankOverview().transactions[0].category,'Alimentação');
 assert.deepEqual(db.integrity(),['ok']);db.close();fs.rmSync(dir,{recursive:true,force:true});
});
