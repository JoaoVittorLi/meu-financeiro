'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');const os=require('node:os');const path=require('node:path');
const {FinanceDB,matchRule,normalizeLabel}=require('../electron/db.cjs');
const ITEM='11111111-1111-4111-8111-111111111111';
const ACCOUNT='22222222-2222-4222-8222-222222222222';
const TX='33333333-3333-4333-8333-333333333333';
const settings={opening:0,income:0,fixed:0,existing:0,reserve:0};
const manual=(category='Alimentação')=>({transactions:[{id:'manual1',date:'2026-11-06',kind:'expense',amount:3590,description:'IFOOD * restaurante',category,origin:'manual'}],budgets:{[category]:5000},settings});
const bank=(description='Ifood pago')=>({item:{status:'UPDATED'},data:[{account:{id:ACCOUNT,name:'Itaú',balance:450.65},transactions:[{id:TX,date:'2026-11-06',amount:-29.99,description,status:'POSTED',category:'Outros'}]}]});
test('categorias personalizadas persistem e orçamentos dinâmicos sobrevivem reinicialização',()=>{
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'mf-cat-'));const file=path.join(dir,'f.sqlite');
 let db=new FinanceDB(file);db.upsertCategory({name:'Pets',color:'#ad83ff'});
 db.save('real',manual('Pets'));assert.equal(db.load('real').budgets.Pets,5000);
 db.close();db=new FinanceDB(file);assert(db.listCategories().categories.some(c=>c.name==='Pets'));
 assert.equal(db.load('real').transactions[0].category,'Pets');db.close();fs.rmSync(dir,{recursive:true,force:true});
});
test('regras aplicam em banco já sincronizado e são insensíveis a acentos e maiúsculas',()=>{
 const db=new FinanceDB(':memory:');db.ingestBank(ITEM,bank('IFOOD Instituição de Pagamento'));
 assert.equal(db.bankOverview().transactions[0].category,'Outros');
 db.upsertRule({pattern:'ifood',category:'Alimentação',matchMode:'contains',scope:'bank',priority:100});
 assert.equal(db.bankOverview().transactions[0].category,'Alimentação');
 assert.equal(db.bankOverview().transactions[0].categorySource,'rule');
 assert.equal(normalizeLabel('  alimentação  '),'ALIMENTACAO');
 db.close();
});
test('menor prioridade vence e regra mais antiga desempata',()=>{
 const db=new FinanceDB(':memory:');db.ingestBank(ITEM,bank('Pix Ifood Restaurante'));
 db.upsertRule({pattern:'PIX',category:'Contas',matchMode:'contains',scope:'bank',priority:30});
 db.upsertRule({pattern:'IFOOD',category:'Alimentação',matchMode:'contains',scope:'bank',priority:10});
 assert.equal(db.bankOverview().transactions[0].category,'Alimentação');
 db.upsertRule({pattern:'PIX',category:'Outros',matchMode:'contains',scope:'bank',priority:10});
 assert.equal(db.bankOverview().transactions[0].category,'Alimentação');
 assert.equal(matchRule('Uber * Viagem','manual',db.listCategories().rules),null);
 db.close();
});
test('correção individual prevalece sobre regra e sincronização repetida',()=>{
 const db=new FinanceDB(':memory:');db.ingestBank(ITEM,bank());
 const rule=db.upsertRule({pattern:'ifood',category:'Alimentação',matchMode:'contains',scope:'bank',priority:100}).rules[0];
 db.overrideBankCategory({accountId:ACCOUNT,externalId:TX,category:'Lazer'});
 db.ingestBank(ITEM,bank('IFood alterado pela API'));
 assert.equal(db.bankOverview().transactions[0].category,'Lazer');
 assert.equal(db.bankOverview().transactions[0].categorySource,'manual');
 db.overrideBankCategory({accountId:ACCOUNT,externalId:TX,category:null});
 assert.equal(db.bankOverview().transactions[0].category,'Alimentação');
 db.deleteRule(rule.id);
 assert.equal(db.bankOverview().transactions[0].category,'Outros');
 db.close();
});
test('renomear categoria customizada preserva manual, orçamento, regras e overrides',()=>{
 const db=new FinanceDB(':memory:');db.upsertCategory({name:'Delivery',color:'#aabbcc'});
 db.save('real',manual('Delivery'));db.ingestBank(ITEM,bank());
 db.upsertRule({pattern:'ifood',category:'Delivery',matchMode:'contains',scope:'both',priority:1});
 db.overrideBankCategory({accountId:ACCOUNT,externalId:TX,category:'Delivery'});
 db.upsertCategory({previousName:'Delivery',name:'Comida pronta',color:'#667788'});
 assert.equal(db.load('real').transactions[0].category,'Comida pronta');
 assert.equal(db.load('real').budgets['Comida pronta'],5000);
 assert.equal(db.listCategories().rules[0].category,'Comida pronta');
 assert.equal(db.bankOverview().transactions[0].category,'Comida pronta');
 assert.deepEqual(db.integrity(),['ok']);db.close();
});
test('categorias em uso não são excluídas; categorias padrão são protegidas',()=>{
 const db=new FinanceDB(':memory:');db.upsertCategory({name:'Investimentos',color:'#bb44aa'});
 db.save('real',manual('Investimentos'));
 assert.throws(()=>db.deleteCategory('Investimentos'),/em uso/);
 assert.throws(()=>db.deleteCategory('Moradia'),/padrão/);
 db.save('real',{transactions:[],budgets:{Investimentos:0},settings});
 assert.equal(db.deleteCategory('Investimentos').categories.some(x=>x.name==='Investimentos'),false);
 db.close();
});
test('corrupção de regra/categoria é recusada sem afetar dados',()=>{
 const db=new FinanceDB(':memory:');db.save('real',manual());
 assert.throws(()=>db.upsertRule({pattern:'A',category:'Categoria inexistente',priority:1,scope:'bank',matchMode:'contains'}),/não existe/);
 assert.throws(()=>db.upsertCategory({name:'Alimentação',color:'#aabbcc'}),/existe/);
 assert.equal(db.load('real').transactions.length,1);
 assert.deepEqual(db.integrity(),['ok']);db.close();
});
test('escopos separados para banco e lançamentos manuais',()=>{
 const db=new FinanceDB(':memory:');
 db.upsertRule({pattern:'UBER',category:'Transporte',priority:1,scope:'manual',matchMode:'contains'});
 const rules=db.listCategories().rules;
 assert.equal(matchRule('UBER Trip','manual',rules),'Transporte');
 assert.equal(matchRule('UBER Trip','bank',rules),null);
 db.close();
});
